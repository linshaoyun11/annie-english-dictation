function w(
  grade: number,
  unit: number,
  english: string,
  phonetic: string,
  chinese: string
): WordEntry {
  return mk(grade, unit, "word", english, phonetic, chinese);
}

function p(
  grade: number,
  unit: number,
  english: string,
  phonetic: string,
  chinese: string
): WordEntry {
  return mk(grade, unit, "phrase", english, phonetic, chinese);
}

