function normText(s: string): string {
  return s.trim().toLowerCase();
}

/** 宽松比对：忽略空格与连字符（ice-cream ≡ ice cream） */
function looseKey(s: string): string {
  return normText(s).replace(/[\s-]+/g, "");
}

export interface KebiaoBuildOpts {
  /** 教材已有词条英文文本集合（小写） */
  existingTexts: Set<string>;
  /** 词条工厂（决定 id 前缀与计数器） */
  make: EntryFactory;
  /** 某年级现有最大单元号（新单元号从 +1 开始） */
  lastUnitOfGrade: (grade: number) => number;
  /** 二级（小学）词汇分配到哪些年级 */
  elemGrades: number[];
  /** 三级（初中）词汇分配到哪些年级 */
  midGrades: number[];
  /** 每单元词数（默认 15） */
  wordsPerUnit?: number;
}

/**
 * 把课标缺失词分配成若干「课标词汇」单元（按年级内字母序）。
 * 返回的单元数组本身按 grade、unit 升序，可直接按年级插入教材数组。
 */
export function buildKebiaoUnits(opts: KebiaoBuildOpts): UnitInfo[] {
  const { existingTexts, make, lastUnitOfGrade, elemGrades, midGrades } = opts;
  const perUnit = opts.wordsPerUnit ?? 15;

  const looseExisting = new Set<string>();
  for (const t of existingTexts) looseExisting.add(looseKey(t));

  const hasWord = (w: string) =>
    existingTexts.has(normText(w)) || looseExisting.has(looseKey(w));

  const elemWords = KEBIAO_BANK.filter((w) => w.band === 2 && !hasWord(w.en));
  const midWords = KEBIAO_BANK.filter((w) => w.band === 3 && !hasWord(w.en));
  elemWords.sort((a, b) => a.en.localeCompare(b.en));
  midWords.sort((a, b) => a.en.localeCompare(b.en));

  const units: UnitInfo[] = [];

  const buildGradeUnits = (
    grade: number,
    words: BankWord[],
    labelPrefix: string
  ) => {
    if (!words.length) return;
    let unit = lastUnitOfGrade(grade) + 1;
    for (let i = 0; i < words.length; i += perUnit) {
      const chunk = words.slice(i, i + perUnit);
      const first = chunk[0].en[0].toUpperCase();
      const last = chunk[chunk.length - 1].en[0].toUpperCase();
      const range = first === last ? first : `${first}-${last}`;
      const entries = chunk.map((w) => {
        const type: EntryType = w.en.trim().includes(" ") ? "phrase" : "word";
        return make(grade, unit, type, w.en, w.ph, w.cn);
      });
      units.push({
        grade,
        unit,
        title: `${labelPrefix} ${range}`,
        entries,
      });
      unit += 1;
    }
  };

  // 小学段：按年级均分（字母序连续切块）
  if (elemGrades.length) {
    const per = Math.ceil(elemWords.length / elemGrades.length);
    elemGrades.forEach((g, idx) => {
      buildGradeUnits(
        g,
        elemWords.slice(idx * per, (idx + 1) * per),
        "课标词汇"
      );
    });
  }
  // 初中段：按年级均分
  if (midGrades.length) {
    const per = Math.ceil(midWords.length / midGrades.length);
    midGrades.forEach((g, idx) => {
      buildGradeUnits(
        g,
        midWords.slice(idx * per, (idx + 1) * per),
        "课标词汇"
      );
    });
  }

  return units;
}

/** 把新单元按年级插入到既有单元数组（保持 grade/unit 升序） */
export function insertKebiaoUnits(
  curriculum: UnitInfo[],
  newUnits: UnitInfo[]
): void {
  for (const u of newUnits) {
    let at = curriculum.findIndex((x) => x.grade > u.grade);
    if (at === -1) at = curriculum.length;
    curriculum.splice(at, 0, u);
  }
}

/**
 * 便捷封装：为某教材词库补全课标缺失词（原地插入新单元）。
 * 必须在教材数组字面量求值完成之后调用，以保证 mk 计数器顺序稳定。
 */
export function applyKebiaoTo(
  curriculum: UnitInfo[],
  make: EntryFactory,
  elemGrades: number[],
  midGrades: number[]
): void {
  const existing = new Set<string>();
  for (const u of curriculum)
    for (const e of u.entries) existing.add(e.english.toLowerCase());
  const lastUnit = (g: number) =>
    curriculum
      .filter((u) => u.grade === g)
      .reduce((m, u) => Math.max(m, u.unit), 0);
  const units = buildKebiaoUnits({
    existingTexts: existing,
    make,
    lastUnitOfGrade: lastUnit,
    elemGrades,
    midGrades,
  });
  insertKebiaoUnits(curriculum, units);
}
